#!/usr/bin/env python3
"""Build hashverify/REPORT.md and hashverify/counts.csv from the run directories (no RPC).

Uses the newest run of each stage in --data (headers-N, public-N, local-N, tamper-N): every
number in the report is read from that run's summary.csv / per-ledger CSV, never typed by hand.
Every mismatch, chain break or disagreement row is listed with its ledger index and both hashes.
"""

import argparse
import csv
import os
import re
import sys


def latest(data, stage):
    runs = []
    for name in os.listdir(data):
        m = re.fullmatch(rf"{stage}-(\d+)", name)
        marker = "" if stage == "tamper" else "summary.csv"
        if m and os.path.exists(os.path.join(data, name, marker)):
            runs.append((int(m.group(1)), name))
    return os.path.join(data, max(runs)[1]) if runs else None


def summary(d):
    with open(os.path.join(d, "summary.csv")) as fh:
        return {r["metric"]: r["value"] for r in csv.DictReader(fh)}


def rows(d, name):
    with open(os.path.join(d, name)) as fh:
        return list(csv.DictReader(fh))


def cells(*c):
    return "| " + " | ".join(str(x) for x in c) + " |"


def header_problems(d):
    bad = []
    for r in rows(d, "headers.csv"):
        if r["hash_ok"] != "True":
            bad.append(cells(r["source"], r["ledger_index"], "hash", r["reported_hash"], r["computed_hash"]))
        if r["parent_ok"] == "False":
            bad.append(
                cells(r["source"], r["ledger_index"], "parent link", r["parent_hash"], r["prev_computed"])
            )
        if r["agree"] == "False" and r["source"] == "local":
            bad.append(cells("both", r["ledger_index"], "disagree", r["computed_hash"], r["other_computed"]))
    return bad


def tree_problems(d):
    bad = []
    for r in rows(d, "txtree.csv"):
        failed = [c for c in ("header_ok", "hash_ok", "txids_ok", "root_ok") if r[c] != "True"]
        if failed:
            bad.append(
                f"| {r['ledger_index']} | {','.join(failed)} | {r['reported_root']} | {r['computed_root']} |"
            )
    return bad


def table(pairs):
    return ["| metric | value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in pairs]


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--data", default="hashverify/data")
    p.add_argument("--out", default="hashverify")
    a = p.parse_args(argv)
    hdr, pub, loc, tam = (latest(a.data, s) for s in ("headers", "public", "local", "tamper"))
    if not (hdr and pub):
        print("need at least one headers-N and one public-N run", file=sys.stderr)
        return 2
    counts = []
    md = ["# hashverify results", ""]
    md.append("Generated by `hashverify/report_hashverify.py` from the run directories below; every value is")
    md.append("read from a run's summary.csv or per-ledger CSV. Verdict lines are in `hashverify/logs/`.")
    md.append("")
    for title, d, probs in (
        ("Header hash chain: own node + public RPC, whole complete_ledgers overlap", hdr, header_problems),
        ("Transaction trees: public RPC, 1 h slice + random sample", pub, tree_problems),
        ("Transaction trees: own node, every retained ledger", loc, tree_problems),
    ):
        if d is None:
            continue
        s = summary(d)
        run = os.path.basename(d)
        md += [f"## {title} (`{run}`)", ""] + table(s.items()) + [""]
        counts += [(run, k, v) for k, v in s.items()]
        bad = probs(d)
        if probs is header_problems:
            md += ["Findings (source, ledger, check, reported/local, computed/public):", ""]
            md += (
                (["| source | ledger | check | a | b |", "|---|---|---|---|---|"] + bad) if bad else ["none"]
            )
        else:
            md += ["Mismatched ledgers (ledger, failed checks, reported root, computed root):", ""]
            md += (
                (["| ledger | failed | reported_root | computed_root |", "|---|---|---|---|"] + bad)
                if bad
                else ["none"]
            )
        md.append("")
    if tam:
        md += [f"## Real-data negative controls (`{os.path.basename(tam)}`)", ""]
        md += ["| control | findings / mismatched ledgers | expected |", "|---|---|---|"]
        found = []
        expect = {
            "headers-coins": "3 (HASH_MISMATCH N, DISAGREE N, CHAIN_BREAK N+1)",
            "headers-parent": "4 (HASH_MISMATCH N, CHAIN_BREAK N, DISAGREE N, CHAIN_BREAK N+1)",
            "txtree-blob": "1 ledger (txids + root)",
            "headers-clean": "0",
            "txtree-clean": "0",
        }
        for sub in sorted(os.listdir(tam)):
            d = os.path.join(tam, sub)
            if not os.path.isfile(os.path.join(d, "summary.csv")):
                continue
            s = summary(d)
            val = s.get("findings", s.get("mismatched_ledgers"))
            counts.append((f"{os.path.basename(tam)}/{sub}", "findings", val))
            md.append(f"| {sub} | {val} | {expect.get(sub, '?')} |")
            found += [f"| {sub} {b}" for b in (header_problems(d) if "findings" in s else tree_problems(d))]
        md += [
            "",
            "Control findings (headers: source, ledger, check, reported/parent/local, computed/public;",
        ]
        md += ["tx trees: ledger, failed checks, reported root, computed root):", ""]
        md += ["| control | | | | | |", "|---|---|---|---|---|---|"] + found + [""]
    with open(os.path.join(a.out, "REPORT.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    with open(os.path.join(a.out, "counts.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["run", "metric", "value"])
        w.writerows(counts)
    print(f"wrote {a.out}/REPORT.md and {a.out}/counts.csv ({len(counts)} values)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
